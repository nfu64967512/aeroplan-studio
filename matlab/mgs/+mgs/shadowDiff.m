function D = shadowDiff(live, c, opts)
%MGS.SHADOWDIFF  Where does the model part company with the vehicle?
%
%   D = mgs.shadowDiff('runs/shadow/RRX.ndjson', c)
%   D = mgs.shadowDiff(L, c, 'uav', 2, 'freerun', true)
%
%   Compares the model against a recorded live sortie at three points in the
%   chain and says WHICH LAYER diverged first.  The point is attribution, not
%   measurement: any two trajectories diverge, and knowing that they did has
%   never been actionable here.
%
% ===========================================================================
%   THE ONE THING THAT MAKES THIS WORK: EVERY LAYER IS DRIVEN BY LIVE INPUTS.
%
%   The obvious implementation -- seed the model at release, let it run, and
%   compare the two trajectories -- CANNOT ATTRIBUTE.  It was built that way
%   first and measured: perturbing pn.los_floor from 1.0 to 0.5 produced
%   rms 0.518 / 0.518 / 0.513 / 0.510 deg at the four layers, i.e. the same
%   number everywhere.  So did perturbing the drag coefficient.  Once the two
%   vehicles are in different STATES, every layer sees that one state
%   difference and none of them sees its own.
%
%   So this compares ONE STEP AT A TIME, each block fed the live inputs:
%
%     L1 GUIDANCE   mgs.guidance( LIVE measurement )      vs live cmd
%                   Same measurement in.  A difference is the LAW.
%                   ⚠️ NOT a perfectly clean isolate: the law reads MEASURED
%                   PITCH for its angle-of-attack estimate (tot_node.py:2871),
%                   so an attitude difference caused further downstream feeds
%                   back into L1.  Measured on the synthetic fixture: a pure
%                   clamp-layer injection still moves L1 by rms 4.34 deg, but
%                   0.1 s LATER than L2.  Attribution therefore rests on the
%                   ORDER of the first excursions, not on a layer being silent.
%
%     L2 CLAMP      mgs.autopilot( LIVE cmd, LIVE state ) vs live nav_*
%                   Same command and same attitude in.  A difference is our
%                   model of the ArduPlane clamp chain.
%
%     L3 PLANT      mgs.airframe( LIVE state, LIVE nav ) vs d(live state)/dt
%                   Same state and same actuator in.  A difference is the
%                   PLANT -- and this is the layer the gamma hook in
%                   mgs.params belongs to.
%
%   This is one-step prediction error (equation error), not simulation error.
%   Simulation error is still computed when 'freerun' is on, and reported
%   separately as D.freerun -- it is a useful headline and it is NEVER used
%   for attribution.
%
% ===========================================================================
%   ATTRIBUTION NEEDS BOTH AN ABSOLUTE AND A RELATIVE THRESHOLD, and requiring
%   only one of them is wrong in a way that was measured, not guessed:
%
%     relative only -- the pitch COMMAND is a smooth signal whose deviation
%       from its own median is only about 0.18 deg over a whole dive.  On the
%       synthetic null case (a stream generated by this very model, so the
%       true divergence is zero) a 0.03 deg replay residue normalised to 17%
%       and the tool reported a divergence at L1.  A false positive on the
%       null case makes every other verdict worthless.
%
%     absolute only -- the layers are in deg, deg, deg/s and m/s2.  One
%       threshold in degrees silently privileges whichever layer happens to
%       swing widest.
%
%   So a layer counts as diverged only when |err| clears BOTH.  The absolute
%   floors default to roughly 15x the measured null-case noise:
%       L1 0.5 deg   L2 0.5 deg   L3 0.5 deg/s   L3b 1.0 m/s2
%   Null case for reference: 0.013 deg, 0.011 deg, 0.003 deg/s, 0.026 m/s2.
%
%   D.layer(k)  .name .avail .why_unavail .units
%               .t .model .live .err .rms .p95 .scale .t_first
%   D.attribution      the earliest layer with a sustained normalised excursion
%   D.freerun          simulation error, if requested
%   D.ic               the live release state used for the freerun
%
%   A layer with no live data is marked avail = false and is NEVER scored.
%   "No divergence" for a layer that was never recorded is the same class of
%   error as a stale parameter and easier to make.
%
%   See also MGS.PARSESTREAM, MGS.RECORDSTREAM, MGS.SYNTHSTREAM.

arguments
    live
    c = mgs.params()
    opts.uav (1,1) double = 1
    opts.render (1,1) logical = true
    opts.thresh (1,1) double = 0.15     % RELATIVE excursion that counts
    opts.thresh_abs (1,:) double = [0.5 0.5 0.5 1.0]   % ABSOLUTE, per layer
    opts.hold_s (1,1) double = 0.5      % ... sustained this long
    opts.t_release (1,1) double = NaN
    opts.freerun (1,1) logical = false
    opts.diff_win (1,1) double = 5      % half-window for the live derivative
    opts.warmup_s (1,1) double = 0.5    % see WARM-UP below
    opts.post_s (1,1) double = 1.0      % keep this long past the datum crossing
end

if ischar(live) || isstring(live), L = mgs.parseStream(live); else, L = live; end
check_inputs(L);

% ---- the vehicle, in the tangent plane tot_node uses ----------------------
[T, nn, ee, zz] = vehicle_frame(L, c, opts);
[kRel, relHow] = find_release(T, zz, L, opts, opts.uav);
tRel = T.t(kRel);
t = T.t - tRel;

% ---- state and inputs, per live sample ------------------------------------
vh  = hypot(T.vn, T.ve);
V   = hypot(vh, T.vd);
gam = atan2(-T.vd, max(vh, 1e-3));
psi = atan2(T.ve, T.vn);
th  = deg2rad(T.pitch_deg);
phi = deg2rad(T.roll_deg);

% WARM-UP.  The first tick after release is a startup transient on both sides:
% the flight controller has not yet acted on a command, and the model's own
% seeding deliberately reproduces that (nav_pitch = 0 until have_cmd).  On the
% synthetic null case that one sample alone moved the L2 rms from 0.04 to 0.97
% -- a single sample deciding a headline is exactly the kind of number this
% project has been burned by.  Skipped, and the skip is stated.
% ⚠️⚠️ STOP AT THE DATUM CROSSING.  SITL does not terminate an airframe that
% reaches the water: it keeps flying it under the surface and back up, and the
% first real recording carried 930 s of that (amsl down to -45 m) after a 37 s
% dive.  Scoring it drove the L3 gamma-dot rms to 532 deg/s, which is not a
% divergence, it is drowned-airframe garbage.  Same shape as the second-pass
% contamination that once turned 32.6 m into 22.6 m.
kEnd = numel(t);
kCross = find(zz <= 0 & t > opts.warmup_s, 1, 'first');
if ~isempty(kCross)
    kEnd = min(numel(t), kCross + round(opts.post_s / max(median(diff(t)), 1e-3)));
end
sel = t >= opts.warmup_s;
sel(kEnd+1:end) = false;
idx = find(sel);
if numel(idx) < 10
    error('mgs:shadowDiff:short', ...
        ['only %d samples after the %.2f s warm-up.  Either the recording is ' ...
         'too short or the release was detected in the wrong place.'], ...
        numel(idx), opts.warmup_s);
end

% ============================ L1 GUIDANCE ==================================
% Drive mgs.guidance with the LIVE measurement at every tick, carrying its own
% internal state forward -- exactly as tot_node does.  The alpha low-pass and
% the freeze latch have memory, so they must be carried, not re-seeded.
% ⚠️ THE GUIDANCE REPLAY RATE IS NOT FREE.
% The alpha low-pass gain is k = tick_dt / alpha_tau (tot_node.py:2876), so
% replaying the law at anything other than the node's own 20 Hz gives a
% DIFFERENT FILTER and a systematic L1 error that is entirely our own.
% Measured on the synthetic null case (warm-up skipped, so these are the
% numbers demo_shadow reproduces): L1 rms 0.013 deg at 20 Hz, 0.037 at 10 Hz,
% 0.023 at 50 Hz.  20 Hz is the lowest, and it is the only rate that is
% principled -- but note the margin over 50 Hz is small, so a rate mismatch
% is a caution about small L1 readings, not a disqualification of large ones.
liveHz = 1/median(diff(t(idx)));
nodeHz = 1/c.pn.tick_dt;
if abs(liveHz - nodeHz) > 0.05*nodeHz
    warning('mgs:shadowDiff:rate', ...
        ['the recording is %.1f Hz but the node ticks at %.1f Hz.  The ' ...
         'alpha low-pass is rate dependent, so the L1 guidance layer now ' ...
         'carries a replay artefact of its own -- do not attribute a small ' ...
         'L1 divergence at this rate.  Record with --state-hz %g.'], ...
        liveHz, nodeHz, nodeHz);
end
D_rate = struct('live_hz', liveHz, 'node_hz', nodeHz);

gs = mgs.guidance();
gs.phase = 'dive';
gs.dive_T = dive_T_from(L, tRel);
mdlCmdPitch = nan(numel(idx), 1);
mdlCmdRoll  = nan(numel(idx), 1);
mdlNz       = nan(numel(idx), 1);
mdlLosAct   = nan(numel(idx), 1);
for j = 1:numel(idx)
    k = idx(j);
    m = struct('n', nn(k), 'e', ee(k), 'z', zz(k), ...
               'vn', T.vn(k), 've', T.ve(k), 'vd', T.vd(k), 'pitch', th(k));
    m.d = max(1e-3, hypot(m.n, m.e));  m.h = m.z;
    m.R = max(1e-3, hypot(m.d, m.h));  m.vh = hypot(m.vn, m.ve);
    m.lam_dot = 0; m.sig_dot = 0; m.Vc = 0;   % stot_guidance recomputes these
    [cmd, gs, dbg] = mgs.guidance(m, gs, t(k), c);
    mdlCmdPitch(j) = rad2deg(cmd.pitch);
    mdlCmdRoll(j)  = rad2deg(cmd.roll);
    mdlNz(j)       = getf(dbg, 'nz', NaN);
    mdlLosAct(j)   = double(getf(dbg, 'los_active', false));
end

% ============================ L2 CLAMP =====================================
% Drive mgs.autopilot with the LIVE command and the LIVE attitude.  If the
% recording has no live command, this layer cannot be isolated -- fall back is
% NOT to use the model's own command, because that would fold L1's error into
% L2 and make both look like one problem.
haveCmd = L.have.command;
mdlNavPitch = nan(numel(idx), 1);
mdlNavRoll  = nan(numel(idx), 1);
if haveCmd
    ap = mgs.autopilot();  ap.thr_pc_prev = NaN;
    dt_fc = 1/c.fc.loop_hz;
    for j = 1:numel(idx)
        k = idx(j);
        cmdLive = struct('roll',  deg2rad(T.cmd_roll_deg(k)), ...
                         'pitch', deg2rad(T.cmd_pitch_deg(k)), ...
                         'thr',   nz_or(T.cmd_thrust(k), 0.5));
        x = [nn(k); ee(k); zz(k); V(k); gam(k); psi(k); th(k); 0; phi(k); 0];
        [u, ap] = mgs.autopilot(cmdLive, x, ap, dt_fc, c);
        mdlNavRoll(j)  = rad2deg(u(1));
        mdlNavPitch(j) = rad2deg(u(2));
    end
end

% ============================ L3 PLANT =====================================
% Drive mgs.airframe with the LIVE state and the LIVE actuator, and compare
% its derivative against the live state differentiated.  Comparing gamma-dot
% rather than gamma is the point: an integrated quantity carries every earlier
% error with it, which is what destroys attribution.
% ⚠️⚠️ THE PLANT NEEDS ALL THREE ACTUATOR INPUTS, AND THROTTLE IS ONE OF THEM.
% An earlier version substituted thr = 0.5 when the throttle was unknown and
% scored L3 anyway.  That is fabricating an input and then reporting the
% consequence as a divergence -- the exact failure this whole tool exists to
% prevent, and I shipped it for one run.  On the first real recording it put
% 21.8-34.3 deg/s of gamma-dot "divergence" on the board, an unknown fraction
% of which was the made-up throttle.
%
% There is no throttle in what the bridge currently records: nav_controller_output
% has none, imu/data has none, and ATTITUDE_TARGET (which carries it) is not
% streamed by ArduPlane unless SET_MESSAGE_INTERVAL asks for msg 83.
% So: no throttle -> L3 is NOT SCORED, and says why.
% THE THROTTLE COMES FROM VFR_HUD, NOT FROM ATTITUDE_TARGET.
% VFR_HUD.throttle is the APPLIED throttle in percent -- after the firmware's
% clamp and slew limiter -- which is exactly the actuator the airframe saw.
% ATTITUDE_TARGET.thrust is the COMMAND side and a different quantity, and
% ArduPlane does not stream it unless asked.
haveThr = ismember('throttle_pc', T.Properties.VariableNames) && ...
          any(isfinite(T.throttle_pc(idx)));
haveNav = L.have.clamp && haveThr;
plantWhy = '';
if ~L.have.clamp
    plantWhy = 'no nav_controller_output, so the actuator input is unknown';
elseif ~haveThr
    plantWhy = ['no throttle in the recording (VFR_HUD absent -- is the ' ...
        'vfr_hud plugin in the MAVROS allowlist?).  Refusing to substitute ' ...
        'a value: the plant would then be scored against an input nobody sent'];
end
mdlGamDot = nan(numel(idx), 1);
mdlVdot   = nan(numel(idx), 1);
if haveNav
    for j = 1:numel(idx)
        k = idx(j);
        x = [nn(k); ee(k); zz(k); V(k); gam(k); psi(k); th(k); 0; phi(k); 0];
        u = [deg2rad(T.nav_roll_deg(k)); deg2rad(T.nav_pitch_deg(k)); ...
             T.throttle_pc(k)];          % already a percentage
        dx = mgs.airframe(x, u, c);
        mdlGamDot(j) = rad2deg(dx(5));
        mdlVdot(j)   = dx(4);
    end
end
liveGamDot = cdiff(t(idx), rad2deg(gam(idx)), opts.diff_win);
liveVdot   = cdiff(t(idx), V(idx),            opts.diff_win);

% ============================ assemble =====================================
D = struct();
D.uav = opts.uav;
D.n_live = numel(idx);
D.t_release_unix = tRel;
D.t = t(idx);
D.rate = D_rate;
D.release_detector = relHow;

D.layer = struct('name', {}, 'avail', {}, 'why_unavail', {}, 'units', {}, ...
                 't', {}, 'model', {}, 'live', {}, 'err', {}, 'rms', {}, ...
                 'p95', {}, 'scale', {}, 'thr_abs', {}, 'live_hz', {}, ...
                 't_first', {});

ta = opts.thresh_abs;
if numel(ta) == 1, ta = repmat(ta, 1, 4); end
if numel(ta) < 4
    error('mgs:shadowDiff:thresh', ...
        'thresh_abs needs 1 or 4 entries (L1 L2 L3 L3b), got %d', numel(ta));
end

D.layer(1) = mk('L1 guidance  pitch cmd', 'deg', L.have.command, ...
    ['no setpoint_raw/target_attitude -- mavros_msgs was not importable in ' ...
     'the bridge, or the FC does not stream ATTITUDE_TARGET'], ...
    D.t, mdlCmdPitch, T.cmd_pitch_deg(idx), opts, ta(1));

D.layer(2) = mk('L2 clamp     nav_pitch', 'deg', haveCmd && L.have.clamp, ...
    ternary(~haveCmd, ['no live command, so the clamp cannot be isolated ' ...
        'from the guidance'], 'no nav_controller_output in the recording'), ...
    D.t, mdlNavPitch, T.nav_pitch_deg(idx), opts, ta(2));

D.layer(3) = mk('L3 plant     gamma-dot', 'deg/s', haveNav, plantWhy, ...
    D.t, mdlGamDot, liveGamDot, opts, ta(3));

D.layer(4) = mk('L3b plant    Vdot', 'm/s2', haveNav, plantWhy, ...
    D.t, mdlVdot, liveVdot, opts, ta(4));

% ---- attribution, on the normalised error only ---------------------------
D = attribute(D, opts);

% ---- optional free-run, reported but never used for attribution ----------
D.freerun = struct('done', false);
if opts.freerun
    st = struct('n', nn(kRel), 'e', ee(kRel), 'z', zz(kRel), ...
                'vn', T.vn(kRel), 've', T.ve(kRel), 'vd', T.vd(kRel), ...
                'pitch_deg', T.pitch_deg(kRel), 'roll_deg', T.roll_deg(kRel));
    ic = mgs.icFromState(st, c);
    ic.dive_T = dive_T_from(L, tRel);
    scn = struct('tag', sprintf('FREERUN_U%d', opts.uav), ...
                 'tgt', struct('n',0,'e',0,'z',0), 'n', 1, 'ic', ic, ...
                 'T_arr', [], 'calibrated', false, 'notes', {{'free run'}});
    M = mgs.simSwarm(scn, c, 'verbose', false);
    D.ic = ic;
    D.freerun.done = true;
    D.freerun.t_impact_model = M.veh(1).t_impact;
    D.freerun.err_m_model = M.veh(1).err_m;
    mt = M.veh(1).traj;
    gi = interp1(mt.t, mt.gam_deg, D.t, 'linear', NaN);
    e = gi - rad2deg(gam(idx));
    D.freerun.gam_rms = sqrt(mean(e.^2, 'omitnan'));
end

D.summary = render(D, opts, L);
if opts.render, fprintf('%s\n', D.summary); end
end

% =============================================================================
function Lr = mk(name, units, avail, why, t, model, liveVec, opts, thrAbs)
Lr = struct('name', name, 'avail', logical(avail), 'why_unavail', '', ...
            'units', units, 't', [], 'model', [], 'live', [], 'err', [], ...
            'rms', NaN, 'p95', NaN, 'scale', NaN, 'thr_abs', thrAbs, ...
            'live_hz', NaN, 't_first', NaN);
if ~avail
    Lr.why_unavail = why; return;
end
ok = isfinite(model) & isfinite(liveVec);
if ~any(ok)
    Lr.avail = false;
    Lr.why_unavail = 'no overlapping finite samples';
    return;
end
Lr.t = t(ok); Lr.model = model(ok); Lr.live = liveVec(ok);
Lr.err = Lr.live - Lr.model;
% EFFECTIVE update rate of the LIVE signal, not the sample rate.  MAVROS
% re-publishes a held value, and the bridge re-emits at its own rate, so a
% 4 Hz source can arrive looking like 20 Hz.  Count the ticks on which the
% value actually CHANGED -- that is the information rate, and a layer fed a
% slow signal must not be read as if it were fed a fast one.
if numel(Lr.t) > 2
    span = Lr.t(end) - Lr.t(1);
    nchg = sum(abs(diff(Lr.live)) > 0);
    if span > 0, Lr.live_hz = nchg / span; else, Lr.live_hz = NaN; end
else
    Lr.live_hz = NaN;
end
Lr.rms = sqrt(mean(Lr.err.^2));
Lr.p95 = prc(abs(Lr.err), 95);
% Robust scale of the LIVE signal's own excursion.  Not the error's scale --
% normalising an error by itself would make every layer look identical.
Lr.scale = max(prc(abs(Lr.live - median(Lr.live)), 95), 1e-3);
% BOTH thresholds, as a single 0/1 excursion signal.  first_sustained then
% works on that, so the hysteresis applies to the conjunction and not to one
% of the two conditions.
over = (abs(Lr.err) > thrAbs) & (abs(Lr.err)/Lr.scale > opts.thresh);
Lr.t_first = first_sustained(Lr.t, double(over), 0.5, opts.hold_s);
end

% -----------------------------------------------------------------------------
function D = attribute(D, opts)
avail = [D.layer.avail];
firsts = [D.layer.t_first];
cand = find(avail & isfinite(firsts));
if ~any(avail)
    D.attribution = 'unattributable';
    D.attribution_why = 'no layer had live data';
    return;
end
if isempty(cand)
    D.attribution = 'none';
    D.attribution_why = sprintf( ...
        ['no layer cleared BOTH its absolute floor and %.0f%% of its own ' ...
         'signal scale for %.1f s'], 100*opts.thresh, opts.hold_s);
    return;
end
[~, w] = min(firsts(cand));
first = cand(w);
D.attribution = strtrim(D.layer(first).name);
D.attribution_why = sprintf('first sustained normalised excursion at t+%.2f s', ...
    D.layer(first).t_first);
if first > 1 && any(~avail(1:first-1))
    D.attribution_why = [D.attribution_why ...
        '  -- CEILING ONLY: an upstream layer had no data, so this is the ' ...
        'earliest layer that COULD be scored, not necessarily the earliest ' ...
        'that diverged'];
end
end

% -----------------------------------------------------------------------------
function tf = first_sustained(t, e, thresh, hold_s)
tf = NaN;
over = e > thresh;
k = 1;
while k <= numel(over)
    if ~over(k), k = k + 1; continue; end
    j = k;
    while j <= numel(over) && over(j), j = j + 1; end
    if t(min(j, numel(t))) - t(k) >= hold_s, tf = t(k); return; end
    k = j + 1;
end
end

% -----------------------------------------------------------------------------
function d = cdiff(t, y, w)
%CDIFF  Central difference over a +-w window.  A one-sample difference on
%   10 Hz telemetry is mostly quantisation noise, which would swamp the
%   plant layer and make it look like the divergent one every time.
n = numel(y);
d = nan(n, 1);
for k = 1:n
    a = max(1, k-w); b = min(n, k+w);
    if b - a < 2 || t(b) == t(a), continue; end
    d(k) = (y(b) - y(a)) / (t(b) - t(a));
end
end

% -----------------------------------------------------------------------------
function check_inputs(L)
if ~L.have.state
    error('mgs:shadowDiff:nostate', ...
        ['this recording has no per-UAV state at all.  Check MAVROS was up ' ...
         'and the bridge ran with --n > 0.']);
end
if ~L.have.target
    error('mgs:shadowDiff:notarget', ...
        ['no /swarm/tot_gate with a target was recorded, so the tangent ' ...
         'plane origin is unknown and every position would carry the target ' ...
         'offset as a fake divergence.']);
end
end

function [T, nn, ee, zz] = vehicle_frame(L, c, opts)
idx = find([L.uav.id] == opts.uav, 1);
if isempty(idx)
    error('mgs:shadowDiff:uav', 'uav %d not in the recording (have %s)', ...
        opts.uav, mat2str([L.uav.id]));
end
T = L.uav(idx).tbl;
T = T(isfinite(T.t) & isfinite(T.lat) & isfinite(T.lon), :);
if height(T) < 10
    error('mgs:shadowDiff:short', 'only %d usable samples for uav %d', ...
        height(T), opts.uav);
end
[nn, ee] = mgs.ll2ne(T.lat, T.lon, L.tgt.lat, L.tgt.lon);
% ⚠️⚠️ THE DATUM IS c.swarm.tgt_amsl, NOT THE GATE'S alt FIELD.
% /swarm/tot_gate publishes {"target": {..., "alt": self.talt}} and talt is the
% APPROACH altitude parameter (3100 m on this contract), not the elevation of
% the bullseye.  Taking it as the datum puts every altitude 3100 m out, which
% is exactly what happened on the first real recording.  The bullseye is at
% sea level and the contract pins it with target_amsl = 0.0.
ta = c.swarm.tgt_amsl;
if isfinite(L.tgt.alt) && abs(L.tgt.alt - ta) > 1.0
    warning('mgs:shadowDiff:datum', ...
        ['the gate reports target alt %.1f m but the datum in use is %.1f m ' ...
         '(c.swarm.tgt_amsl).  The gate field is talt -- the APPROACH ' ...
         'altitude -- not the target elevation.  Using the contract datum.'], ...
        L.tgt.alt, ta);
end
zz = T.amsl - ta;
end

function [k, how] = find_release(T, zz, L, opts, uavId)
%FIND_RELEASE  The tick PN actually took over, per vehicle.
%
%   Preference order, most authoritative first.  Which one was used is
%   reported, because every downstream number depends on it and a silent
%   choice between three detectors is not a measurement.
%
%   1  an explicit override
%
%   2  the first sample carrying a live ATTITUDE_TARGET.  ⭐ This is the real
%      handover: the flight controller only streams ATTITUDE_TARGET while
%      tot_node is sending SET_ATTITUDE_TARGET, so its first appearance IS
%      the first PN command, per vehicle, directly observed.
%
%   3  tot_status phase == DIVE.  ⚠️ TWO problems, both measured, which is
%      why it is third and not first:
%        - `self.phase` is the SWARM-level phase (tot_node.py:4448): it flips
%          when the FIRST aircraft dives, so with n = 2 releasing at
%          different times both vehicles would be given the first one's
%          release instant.
%        - even per-aircraft, mode=="dive" LEADS the first PN command by a
%          median 8.1 s (range 6.6-9.6, 16/16).  That 8 s is flown by
%          L1/TECS, not by us, and all six observed failures happened in it.
%
%   4  first sustained descent.  Last resort.
how = '';
if isfinite(opts.t_release)
    [~, k] = min(abs(T.t - opts.t_release));
    how = 'explicit override'; return;
end
if ismember('cmd_pitch_deg', T.Properties.VariableNames)
    kk = find(isfinite(T.cmd_pitch_deg), 1, 'first');
    if ~isempty(kk)
        k = kk;
        how = 'first live ATTITUDE_TARGET (the actual PN handover)';
        return;
    end
end
if isfield(L, 'mode') && ~isempty(L.mode)
    sel = L.mode.id == uavId & strcmpi(L.mode.mode, 'dive');
    if any(sel)
        [~, k] = min(abs(T.t - L.mode.t(find(sel, 1, 'first'))));
        how = ['per-vehicle mode==dive -- still ~8 s EARLIER than the first ' ...
               'PN command, but PER VEHICLE'];
        return;
    end
end
if L.have.status
    isDive = strcmpi(L.status.phase, 'DIVE');
    if any(isDive)
        [~, k] = min(abs(T.t - L.status.t(find(isDive, 1, 'first'))));
        how = ['tot_status phase==DIVE -- SWARM-level AND ~8 s early; on the ' ...
               'first real recording this was 7 s before this vehicle''s own ' ...
               'mode==dive'];
        return;
    end
end
dz = [0; diff(zz)];
w = 10;
k = find(movsum(dz < 0, [0 w]) >= w, 1, 'first');
if isempty(k), k = 1; end
how = 'first sustained descent (last resort)';
end

function dT = dive_T_from(L, tRel)
dT = NaN;
if ~L.have.status, return; end
ok = isfinite(L.status.T_arr);
if ~any(ok), return; end
a = L.status.T_arr(ok); tt = L.status.t(ok);
dT = a(find(tt <= tRel, 1, 'last'));
if isempty(dT), dT = a(1); end
end

