%DEMO_ZARCHAN  Zarchan's method, brought into the mgs environment.
%
%   Run:  mgs_setup; demo_zarchan
%
%   Three things, in the order that makes each one interpretable:
%     1  the book as a reference oracle next to our full nonlinear model
%     2  his Ch. 2 sizing ratio on the same run
%     3  his ADDITIVE terminal-angle term against our one-sided min()
%
%   Source of truth for every book reference is matlab/zarchan/_source/
%   zarchan.txt (15,120 lines).  It is gitignored -- it is a copyrighted book,
%   kept locally so the line numbers in matlab/zarchan/README.md stay
%   checkable.  Not NotebookLM: that notebook has been recorded citing this
%   project's own notes back as external literature, with invented numbers.

mgs_setup();
addpath(fullfile(fileparts(which('mgs_setup')), '..', 'zarchan'));

%% 1 -- the book next to us -------------------------------------------------
fprintf('\n===================== 1. book as reference oracle =============\n');
c = mgs.params('swarm.n', 4);
out = mgs.simSwarm(mgs.scenario(c, 'tag', 'ZCHK'), c, 'verbose', false);
X = mgs.zarchan.crosscheck(out, 'render', true);

%% 2 -- Ch. 2 sizing --------------------------------------------------------
fprintf('\n===================== 2. Ch.2 sizing ratio ====================\n');
mgs.zarchan.sizing(out, 'render', true);

%% 3 -- additive terminal angle vs one-sided min() --------------------------
fprintf('\n===================== 3. additive vs min() ====================\n');
fprintf([ ...
    'tot_node combines the PN demand and the terminal-angle demand with\n' ...
    '    gam_cmd = min(gam_cmd_pn, gam_los * los_floor)      tot_node.py:2866\n' ...
    'Zarchan never does.  Ch. 30 (zarchan.txt:10887):\n' ...
    '    nc = 4*Vc*lamdot + 2*Vc*(lam - gamF)/tgo            <- ADDED\n' ...
    'and the same additive shape in Ch. 24, Ch. 28 and Appendix A.\n\n' ...
    'The difference is that min() has ZERO GRADIENT on its active side: while\n' ...
    'the floor is the smaller of the two, moving the sightline changes the\n' ...
    'command by exactly nothing.  mgs.selftest check 4 measures that -- with\n' ...
    'the floor active, doubling n_vert moves gam_cmd by 0 rad.\n\n']);

fprintf('%-24s %-6s %-11s %-11s %-14s\n', ...
    'law', 'hits', 'med err m', 'spread s', 'LOS active');
runs = { ...
    struct('name', 'node (as flown)',        'ov', {{'pn.law', 'node'}}), ...
    struct('name', 'zarchan K=1.0',          'ov', {{'pn.law', 'zarchan_additive', 'pn.shape_gain', 1.0}}), ...
    struct('name', 'zarchan K=2.0 (book)',   'ov', {{'pn.law', 'zarchan_additive', 'pn.shape_gain', 2.0}}), ...
    struct('name', 'zarchan K=4.0',          'ov', {{'pn.law', 'zarchan_additive', 'pn.shape_gain', 4.0}})};
for r = 1:numel(runs)
    cr = mgs.params('swarm.n', 8, runs{r}.ov{:});
    orr = mgs.simSwarm(mgs.scenario(cr, 'tag', 'LAW'), cr, 'verbose', false);
    k = orr.kpi;
    losf = mean(arrayfun(@(v) mean(v.traj.los_active, 'omitnan'), orr.veh));
    if r == 1
        losTxt = sprintf('%.1f%%', 100*losf);
    else
        % The additive law has no floor at all, so printing "0%" here would
        % read as "the floor stopped firing" when it means "there is no floor".
        losTxt = 'n/a (no floor)';
    end
    fprintf('%-24s %-6d %-11.2f %-11.2f %-14s\n', ...
        runs{r}.name, sum(k.hit), k.err_median, k.spread_s, losTxt);
end

fprintf([ '\n' ...
    'NONE OF THE ZARCHAN ROWS HAS EVER FLOWN.  There is no truth data for\n' ...
    'that law and none of the 32-sortie validation transfers to it.  What the\n' ...
    'table is for is deciding whether the additive form is worth a sortie --\n' ...
    'not for concluding that it is better.\n\n' ...
    'Also note his 2.0 is paired with N''=4 out of one optimal control problem,\n' ...
    'and we fly n_vert = 5.  The pairing of those two gains is not something\n' ...
    'the book addresses, so K = 2.0 is a starting point, not a value with\n' ...
    'authority behind it.\n']);
