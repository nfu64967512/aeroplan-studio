#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""D1 test D: closed-loop synthetic -- the fair analogue of the MODEL column.

stot_lagcheck applies the identical pipeline to (a) the flown gamma and (b) the
model's gamma.  The model scores gain 1.385 / corr +0.927 / lag 1.15 s.  Here we
build a synthetic flight in which gamma is generated by a plant of KNOWN lag and
KNOWN authority, driven by a command recomputed from the synthetic gamma at every
step (self-consistent, exactly as in the model), on the REAL (r, z, gs) history.

If a perfect tracker constrained only by the +-7 deg/s cap scores like the model,
then the gate's 0.063-vs-1.385 comparison is a comparison of TRAJECTORIES, and
'the vehicle achieves 6% of commanded' does not follow from it.
"""
from __future__ import annotations
import math, statistics as st
import numpy as np
import d1_replicate as R

PN = R.PN
CAP = np.radians(7.0)


def closed_loop(t, r, z, gs, gam0, tau, cap, nz_lim=None):
    """Self-consistent gamma with a plant of known lag/authority."""
    n = len(t)
    ddot, _ = R.local_slope(t, r, 0.5)
    gam = np.empty(n); gcmd = np.empty(n)
    g = gam0; act = 0.0
    for k in range(n):
        gam[k] = g
        cg = math.cos(g)
        hdot = gs[k] * math.tan(g)
        V = max(1e-3, math.hypot(gs[k], hdot))
        d = max(1e-3, r[k]); h = z[k]; RR = max(1e-3, math.hypot(d, h))
        sig = (hdot * d - h * ddot[k]) / (RR * RR)
        gd = -PN["n_vert"] * sig
        nz = min(PN["nz_max"], max(PN["nz_min"], cg + V * gd / PN["g"]))
        gd = (nz - cg) * PN["g"] / V
        gc = g + gd * PN["lead"]
        if PN["los_floor"] > 0:
            gc = min(gc, -math.atan2(h, max(d, 1e-3)) * PN["los_floor"])
        gcmd[k] = gc
        want = (gc - g) / PN["lead"]
        if cap is not None:
            want = float(np.clip(want, -cap, cap))
        if nz_lim is not None:      # authority expressed as a load-factor band
            lo = (nz_lim[0] - cg) * PN["g"] / V
            hi = (nz_lim[1] - cg) * PN["g"] / V
            want = float(np.clip(want, lo, hi))
        if k + 1 < n:
            dt = t[k + 1] - t[k]
            if not (0.0 < dt <= 0.6):
                dt = 0.05
            act += (want - act) * min(dt / tau, 1.0)
            g += act * dt
            g = max(-1.45, min(1.45, g))
    return gam, gcmd


def score(t, gam, gcmd, lags):
    _, iu = np.unique(t, return_index=True); iu = np.sort(iu)
    tu, gu, cu = t[iu], gam[iu], gcmd[iu]
    y, _ = R.local_slope(tu, gu, 0.5)
    x = (cu - gu) / PN["lead"]
    gain = float(x @ y / max(x @ x, 1e-12))
    xc, yc = x - x.mean(), y - y.mean()
    corr = float(xc @ yc / max(math.sqrt((xc@xc)*(yc@yc)), 1e-12))
    l, rms, _ = R.best_lag(tu, cu, tu, gu, lags)
    return gain, corr, l, math.degrees(rms)


if __name__ == "__main__":
    lags = np.arange(0, 8.0 + 1e-9, 0.05)
    cases = [("perfect     no cap", 0.05, None, None),
             ("tau=1.0 s   no cap", 1.00, None, None),
             ("tau=3.0 s   no cap", 3.00, None, None),
             ("perfect     +-7 deg/s", 0.05, CAP, None),
             ("tau=1.0 s   +-7 deg/s", 1.00, CAP, None),
             ("tau=3.0 s   +-7 deg/s", 3.00, CAP, None),
             ("perfect     nz in [-1,3]", 0.05, None, (-1.0, 3.0)),
             ("tau=1.0 s   nz in [-1,3]", 1.00, None, (-1.0, 3.0))]
    out = {c[0]: dict(g=[], c=[], l=[], r=[], ceil=0) for c in cases}
    real = dict(g=[], c=[], l=[], r=[], ceil=0)
    for tag in R.TAGS:
        d = R.load(tag)
        if len(d["t"]) < 60: continue
        t, gam, r_, z, gs = d["t"], d["gam"], d["r"], d["z"], d["gs"]
        gc, _, _ = R.replay_gamcmd(t, r_, z, gam, gs)
        g_, c_, l_, rm_ = score(t, gam, gc, lags)
        real["g"].append(g_); real["c"].append(c_); real["l"].append(l_)
        real["r"].append(rm_); real["ceil"] += (l_ >= 8.0 - 1e-9)
        for name, tau, cap, nzl in cases:
            gs_syn, gc_syn = closed_loop(t, r_, z, gs, gam[0], tau, cap, nzl)
            a, b, c2, rr = score(t, gs_syn, gc_syn, lags)
            o = out[name]; o["g"].append(a); o["c"].append(b); o["l"].append(c2)
            o["r"].append(rr); o["ceil"] += (c2 >= 8.0 - 1e-9)
    print("=== gate pipeline on SELF-CONSISTENT synthetic flights (known plant) ===")
    print(f"{'plant':<26s}{'gain':>9s}{'corr':>9s}{'lag s':>9s}{'rms deg':>9s}{'at ceil':>9s}")
    for name, tau, cap, nzl in cases:
        o = out[name]
        print(f"{name:<26s}{st.median(o['g']):>9.3f}{st.median(o['c']):>+9.3f}"
              f"{st.median(o['l']):>9.2f}{st.median(o['r']):>9.2f}{o['ceil']:>6d}/32")
    print(f"{'REAL AIRCRAFT':<26s}{st.median(real['g']):>9.3f}"
          f"{st.median(real['c']):>+9.3f}{st.median(real['l']):>9.2f}"
          f"{st.median(real['r']):>9.2f}{real['ceil']:>6d}/32")
    print(f"{'MODEL (gate reported)':<26s}{1.385:>9.3f}{0.927:>+9.3f}"
          f"{1.15:>9.2f}{0.25:>9.2f}{'?':>9s}")
