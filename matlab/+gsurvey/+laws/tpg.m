function [a, s] = tpg(o, p, s)
%GSURVEY.LAWS.TPG  多項式導引(Time-to-go Polynomial Guidance)。
%
%   把加速度指令設計成剩餘時間的多項式,用多出來的自由度**同時**滿足
%   落角約束與終端加速度約束:
%
%       a(t) = c0 + c1·(t_go/T) + c2·(t_go/T)²      (這裡取二階)
%
%   閉式係數(靜止目標、等速、終端加速度 → 0):
%       a_perp = (V²/R)·[ a1·(λ − γ) + a2·(γ_f − γ) ]
%   與 BPNG 同形,但係數由「終端 a = 0」這個額外條件定出來:
%       a1 = 6,  a2 = −4         ← N=6/N=4 的多項式家族
%
%   ⭐ 為什麼對我們有意義:**終端加速度趨零**這個約束正好對應
%      「不要在最後一刻還在硬拉」。我們實測的失效模式之一就是
%      終端還在要求 5.8–6.4 °/s 的 γ̇ 而只做得出 0.6–1.8(追蹤比 0.10–0.31)。
%      一條在終端不要求權限的律,在我們的機體上反而可能落地得比較乾淨。
%
%   ⚠️ 代價是它把權限**前置**了:曲率要在遠端就做完。看模擬時盯
%      aCmd 的時間剖面 —— 它應該與 PN 完全相反(前重後輕)。

vhat = o.v / o.V;

% ⚠️⚠️ 符號要與 o.gamma 同一個慣例(向上為正、俯衝為負)。
%    o.los(3) 在「目標在下方」時是**正**的(NED 的 D 向下),
%    所以 lamV = -atan2(los(3), 水平分量)。第一版寫成
%    -atan2(-los(3), ...) 是雙重負號 ⇒ 視線俯角變成 +26.8° ⇒
%    落角項把飛機**往地面推**,實測 missH 1133 m、落角 +20°(爬升)。
lamV = -atan2(o.los(3), hypot(o.los(1), o.los(2)));    % 視線俯角(俯衝為負)
gam  = o.gamma;
gamF = p.gammaF;

% ⚠️⚠️ 第二項是 (λ − γ_f),**不是** (γ_f − γ)。
%    物理:要達到比視線**更陡**的落角,必須先把飛機拉到視線**上方**
%    (先抬頭)再插下來 —— 那個「過頂」才是落角約束律的特徵形狀。
%    寫成 (γ_f − γ) 會讓它一開始就往下壓 ⇒ 提早插地。
%    第一版實測:missH 295 m、落角 −14.9°(比純 PN 的 −26.8° 還淺),
%    而 track 0.968 < 1 就是「還沒飛到就落地」的指紋。
a1 = 6; a2 = 4;                        % 高一階的多項式家族,整形更積極
aV = (o.V^2 / max(o.R, 1)) * ( a1*(lamV - gam) + a2*(lamV - gamF) );

up = [0; 0; -1];
uV = up - (up.' * vhat) * vhat;
if norm(uV) < 1e-9, uV = [0; 0; 0]; else, uV = uV / norm(uV); end

aH = p.N * o.V * cross(o.omega, vhat);
aH = aH - (aH.' * uV) * uV;

a = aV * uV + aH;
end
