% GSURVEY  純運動學導引律測試台(公式層,**不含**飛控與 SITL)。
%
% ===========================================================================
%  這個套件存在的理由
% ===========================================================================
%  `mgs.simSwarm` 是拿來**對 SITL 的**:它含四個時鐘、飛控夾制鏈、
%  一階姿態迴路,目的是重現真機行為。那正是它的價值,也正是它不適合
%  拿來比較導引律的原因 —— 它會把「律要求了什麼」與「我們的飛機做不做
%  得到」混在同一個數字裡。
%
%  2026-08-26 的調查把這條界線量了出來:
%    * ArduPilot 內迴路實測近乎完美(pitch 增益 0.947、roll 0.956、
%      Pitch→γ 1.006/corr 0.999、升降舵飽和 0/32 趟);
%    * 而終端 γ̇ 追蹤比只有 **0.10–0.31**,實得 n_z 中位 0.77(天花板 3.0)。
%  ⇒ 「律沒效」與「律的指令沒被執行」在真機資料上分不開。
%
%  這個套件把後者**整個拿掉**:指令加速度直接轉動速度向量,沒有姿態
%  迴路、沒有夾制、沒有延遲(除非你顯式打開 `p.tau_a`)。
%  於是它回答的是一個乾淨的問題:**這條律本身,在理想執行器上,
%  能不能交付我們要的東西?**
%
% ---------------------------------------------------------------------------
%  ⚠️⚠️ 單位一律 **公尺 / 公尺每秒 / 弧度**,座標一律 **NED**。
%     `mgs.zarchan.*` 刻意用**英尺**(書上的單位),兩者不可混用 ——
%     脫靶量「18.3」在英尺和公尺都是合理的數字,靜默換算不會當掉,
%     只會產出一個差 3.28 倍的答案。跨界要顯式轉。
%
% ---------------------------------------------------------------------------
%  導引律的介面(**所有律共用,不可各自加參數**)
%
%      aCmd = gsurvey.laws.<name>(o, p, s)
%
%    o  本拍觀測(gsurvey.simulate 組好):
%       .t        [s]      模擬時間
%       .r        [3x1]    目標 − 本機 的相對位置(m, NED)
%       .R        [1]      斜距 |r|
%       .v        [3x1]    本機速度(m/s, NED)
%       .V        [1]      速率 |v|
%       .vt       [3x1]    目標速度(靜止目標為零)
%       .los      [3x1]    視線單位向量 r/R
%       .omega    [3x1]    視線角速度向量 (r × ṙ)/R²
%       .Vc       [1]      接近速率 −ṙ·los
%       .tgo      [1]      幾何剩餘時間 R/max(Vc, eps)
%       .sigma    [1]      前置角(速度向量與視線的夾角, rad)
%       .gamma    [1]      航跡角(向上為正, rad)
%       .peers    [1xN]    struct array:.R .tgo .V .id(協同律用;
%                          **含自己**,以 o.id 辨識)
%       .id       [1]      本機編號
%    p  參數 struct(gsurvey.params)
%    s  本機的律狀態(struct,跨拍持續;律自己決定要存什麼)
%
%    回傳 aCmd [3x1] 指令加速度(m/s², NED)。**不含重力**——
%    重力由 simulate 加,律只回傳導引指令。
%
%  ⚠️ 律**必須**回傳 3x1。二維律請把第三分量設 0 並在檔頭說明。
%  ⚠️ 律**不可以**讀 `o` 以外的東西(不可用 persistent、不可用 global)。
%     跨拍狀態一律走 `s`,否則 n=8 的八架會互相污染,而那是靜默的。
%
% ---------------------------------------------------------------------------
%  檔案
%    gsurvey.params      預設參數(我們的實測工作點)
%    gsurvey.scenario    n 機初始條件
%    gsurvey.simulate    積分器(RK4,終點用割線法求根)
%    gsurvey.metrics     KPI:脫靶、命中時刻散布、落角、需求過載、航跡比
%    gsurvey.runAll      掃過所有律,產比較表與圖
%    gsurvey.laws.*      一律一檔
%
% ---------------------------------------------------------------------------
%  相關記憶:inner-loop-is-not-the-bottleneck、time-term-yes-lateral-no、
%            pure-pn-cannot-fix-spread、we-already-fly-pure-pn
