function p = prc(v, q)
v = sort(v(~isnan(v)));
if isempty(v), p = NaN; return; end
if numel(v) == 1, p = v; return; end
i = 1 + (q/100)*(numel(v)-1);
lo = floor(i); hi = ceil(i);
p = v(lo) + (i-lo)*(v(hi)-v(lo));
end

