function [a, s] = pursuit(o, p, s)
%GSURVEY.LAWS.PURSUIT  純追蹤導引(Pure Pursuit)。
%
%   把速度向量直接轉向視線 —— 沒有前置量。
%       a = K · V · (λ̂ − v̂)_⊥        (只取垂直於 v 的分量)
%
%   放進來的用途是**當對照組**:它是「不含前置量」的極限,而 PN 家族
%   買到的東西就是前置量。對靜止目標它會收斂,但航跡是彎的(尾隨曲線),
%   終端需求加速度在近距離發散。
%
%   ⚠️ 這條在我們的機體上不可用:尾隨曲線的終端曲率 → ∞,
%      而我們的坡度預算只有 ~2 g。放進來是為了讓那個對比看得見。

vhat = o.v / o.V;
e = o.los - vhat;                      % 指向「該轉多少」
e = e - (e.' * vhat) * vhat;           % 只留垂直於速度的分量
K = 2.0 * p.N;                         % 增益取與 PN 同量級,方便對照
a = K * o.V * e / max(o.tgo, 0.5);
end
