function [a, s] = tpn(o, p, s)
%GSURVEY.LAWS.TPN  真比例導引(True Proportional Navigation)。
%
%   a = N · V_c · (ω × λ̂)
%
%   指令加速度**垂直於視線向量**,量值用**接近率** V_c(不是本機速率)。
%   這是教科書上的正典 TPN。
%
%   ⚠️ 在定翼機上難以實現:垂直於 LOS 的指令,分解到機體軸上會有一個
%      **沿速度方向**的分量,而定翼機只有升力(垂直於速度)與推力
%      (沿速度)兩個執行器,前者做不出軸向、後者頻寬遠不夠。
%      這個測試台是理想執行器,所以它會「跑得動」—— 那正是要看的:
%      TPN 在理想執行器上的表現,與 PPN 差多少。差很少的話,
%      「換成 TPN」就更沒有理由了。

a = p.N * o.Vc * cross(o.omega, o.los);
end
